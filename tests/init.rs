#[test]
fn init_ignores_unexpanded_loader_metadata_placeholders() {
    let project = temp_dir("init-expanded-metadata");
    write(
        &project.join("gradle.properties"),
        r#"mod.id=amber
project.minecraft=26.1.2
project.enabled-loaders=fabric,forge,neoforge
"#,
    );
    write(
        &project.join("fabric/src/main/resources/fabric.mod.json"),
        r#"{
  "id": ${mod_id},
  "name": "${mod_name}"
"#,
    );
    write(
        &project.join("forge/src/main/resources/META-INF/mods.toml"),
        r#"
[[mods]]
modId = "${mod_id}"
displayName = "${mod_name}"

[[dependencies.${mod_id}]]
modId = "forge"
"#,
    );

    let output = run_in(&["init"], &project);
    assert!(
        output.status.success(),
        "init should succeed\nstdout:\n{}\nstderr:\n{}",
        String::from_utf8_lossy(&output.stdout),
        String::from_utf8_lossy(&output.stderr)
    );

    let contents =
        fs::read_to_string(project.join("modstage.toml")).expect("modstage.toml should exist");
    assert!(
        contents.contains(r#"name = "amber""#)
            && contents.contains(r#"name = "amber-fabric-26.1.2""#)
            && contents.contains(r#"name = "amber-forge-26.1.2""#)
            && contents.contains(r#"name = "amber-neoforge-26.1.2""#),
        "generated config should use Gradle metadata instead of loader placeholders\n{contents}"
    );
    assert!(
        !contents.contains("${mod_id}") && !contents.contains(r#"name = "forge""#),
        "generated config should not use unresolved placeholders or dependency ids as project names\n{contents}"
    );

    fs::remove_dir_all(project).expect("failed to remove project");
}
