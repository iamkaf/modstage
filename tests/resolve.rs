#[test]
fn resolve_rejects_unsupported_loaders_and_sides_in_launcher_language() {
    let project = temp_project("resolve-invalid-config");
    fs::write(
        project.join("modstage.toml"),
        r#"[project]
name = "resolve-invalid"

[[instance]]
name = "bad-loader"
minecraft = "26.1.2"
loader = "quilt"
sides = ["client"]
"#,
    )
    .expect("failed to write invalid config");

    let bad_loader = run_in(&["resolve", "bad-loader"], &project);
    assert!(
        !bad_loader.status.success(),
        "resolve should reject unsupported loader"
    );
    let stderr = String::from_utf8_lossy(&bad_loader.stderr);
    assert!(
        stderr.contains("instance `bad-loader` uses unsupported loader `quilt`")
            && stderr.contains("vanilla, fabric, forge, neoforge"),
        "unsupported loader error should use launcher language\nstdout:\n{}\nstderr:\n{}",
        String::from_utf8_lossy(&bad_loader.stdout),
        stderr
    );

    fs::write(
        project.join("modstage.toml"),
        r#"[project]
name = "resolve-invalid"

[[instance]]
name = "bad-side"
minecraft = "26.1.2"
loader = "fabric"
sides = ["data"]
"#,
    )
    .expect("failed to write invalid side config");
    let bad_side = run_in(&["resolve", "bad-side"], &project);
    assert!(
        !bad_side.status.success(),
        "resolve should reject unsupported side"
    );
    let stderr = String::from_utf8_lossy(&bad_side.stderr);
    assert!(
        stderr.contains("instance `bad-side` uses unsupported side `data`")
            && stderr.contains("client, server"),
        "unsupported side error should use launcher language\nstdout:\n{}\nstderr:\n{}",
        String::from_utf8_lossy(&bad_side.stdout),
        stderr
    );

    fs::remove_dir_all(project).expect("failed to remove temp project");
}

#[test]
fn resolve_preserves_repositories_and_mods_in_the_lockfile() {
    let project = temp_project("resolve-mods");
    let repo = project.join("repo");
    let teakit_dir = repo
        .join("dev")
        .join("kaf")
        .join("teakit-fabric")
        .join("0.1.0");
    let liteminer_dir = repo
        .join("com")
        .join("iamkaf")
        .join("liteminer")
        .join("liteminer-fabric")
        .join("3.1.0+26.1.2");
    fs::create_dir_all(&teakit_dir).expect("failed to create TeaKit artifact dir");
    fs::create_dir_all(&liteminer_dir).expect("failed to create Liteminer artifact dir");
    fs::write(teakit_dir.join("teakit-fabric-0.1.0.jar"), b"teakit")
        .expect("failed to write TeaKit jar");
    fs::write(
        liteminer_dir.join("liteminer-fabric-3.1.0+26.1.2.jar"),
        b"liteminer",
    )
    .expect("failed to write Liteminer jar");
    fs::write(
        project.join("modstage.toml"),
        format!(
            r#"[project]
name = "resolve-mods"

[repositories]
kaf = "file://{}"
fabric = "https://maven.fabricmc.net"

[[instance]]
name = "liteminer-fabric-26.1.2"
minecraft = "26.1.2"
loader = "vanilla"
sides = ["client", "server"]
mods = [
  "maven:dev.kaf:teakit-fabric:0.1.0",
  "maven:com.iamkaf.liteminer:liteminer-fabric:3.1.0+26.1.2",
]
"#,
            repo.display()
        ),
    )
    .expect("failed to write config");

    let output = run_in(&["resolve", "liteminer-fabric-26.1.2"], &project);
    assert!(
        output.status.success(),
        "resolve should succeed\nstdout:\n{}\nstderr:\n{}",
        String::from_utf8_lossy(&output.stdout),
        String::from_utf8_lossy(&output.stderr)
    );

    let lock =
        fs::read_to_string(project.join("modstage.lock")).expect("modstage.lock should exist");

    for expected in [
        r#"project = "resolve-mods""#,
        r#"instance = "liteminer-fabric-26.1.2""#,
        r#"loader = "vanilla""#,
        &format!(r#"kaf = "file://{}""#, repo.display()),
        r#"fabric = "https://maven.fabricmc.net""#,
        r#""maven:dev.kaf:teakit-fabric:0.1.0""#,
        r#""maven:com.iamkaf.liteminer:liteminer-fabric:3.1.0+26.1.2""#,
        r#"repository = "kaf""#,
    ] {
        assert!(
            lock.contains(expected),
            "lockfile should contain {expected:?}\n{lock}"
        );
    }

    fs::remove_dir_all(project).expect("failed to remove temp project");
}

